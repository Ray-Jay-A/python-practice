# -*- coding: utf-8 -*-
# ============================================================================
# 这个脚本只干一件事：造一份假的「退货工单」Excel，供这周（W3）的 pandas 练习用。
# 跑完之后，你会在「和这个脚本同一个文件夹」里看到一个新文件：
#     工单数据.xlsx
# 里面是 100 行数据、5 列：
#     工单号 / 退货原因 / 退款金额 / 退货日期 / 是否VIP
# ============================================================================


# ---------- 第 1 步：导入要用的工具 ----------
# random   = 生成随机数（造假数据全靠它）
# datetime = 生成"日期"（年-月-日 那种）
# pandas   = 把一堆数据整理成表格，并保存成 Excel
import random
import datetime
import pandas as pd


# ---------- 第 2 步：给随机数定一个"种子" ----------
# 作用：让每次跑出来的 100 行数据都一模一样，方便你做完题跟我对答案。
# （换了 2026 这个数字，造出来的数据就会变，所以别改它。）
random.seed(2026)


# ---------- 第 3 步：准备"退货原因"的候选词 ----------
# 真实业务里每种原因出现的次数不一样（质量问题最多，物流太慢最少）。
# 下面这个写法叫"权重池"：哪个词出现的概率大，就在列表里多写几遍。
#   比如 '质量问题' 写了 30 遍、'物流太慢' 只写 8 遍，
#   那么后面随机抽的时候，'质量问题' 被抽中的机会自然就大得多。
reasons = (
    ['质量问题'] * 30 +
    ['尺码不合适'] * 25 +
    ['发错货'] * 15 +
    ['不喜欢'] * 12 +
    ['商品与描述不符'] * 10 +
    ['物流太慢'] * 8
)


# ---------- 第 4 步：准备一个空列表，等会儿一行一行往里放数据 ----------
rows = []


# ---------- 第 5 步：循环 100 次，每次造出 1 行工单 ----------
for i in range(1, 101):

    # 5.1 工单号：形如 TK2026090001
    #     str(i)     把数字变成文字
    #     .zfill(4)  位数不够 4 位就在前面补 0（1 → 0001，12 → 0012）
    ticket_no = 'TK202609' + str(i).zfill(4)

    # 5.2 退货原因：从上面的 reasons 列表里随机抽 1 个
    reason = random.choice(reasons)

    # 5.3 退款金额：随机取一个 9.9 ~ 599 之间的数，保留 2 位小数
    #     random.uniform(9.9, 599) 取一个带小数的随机数
    #     round(数字, 2)           保留 2 位小数
    amount = round(random.uniform(9.9, 599), 2)

    # 5.4 退货日期：从 2026-09-01 开始，往后随机推 0 ~ 29 天
    #     datetime.date(2026, 9, 1)      → 造出"2026年9月1日"这一天
    #     random.randint(0, 29)          → 随机取一个 0~29 的整数（天数）
    #     datetime.timedelta(days=天数)  → 表示"这么多天"
    #     日期 + 天数                    → 得到一个新的日期
    first_day = datetime.date(2026, 9, 1)
    date = first_day + datetime.timedelta(days=random.randint(0, 29))

    # 5.5 是否VIP：随机在 '是' / '否' 里抽一个
    vip = random.choice(['是', '否'])

    # 5.6 把这一行的 5 个值，按顺序打包成一个列表，塞进 rows 里
    rows.append([ticket_no, reason, amount, date, vip])


# ---------- 第 6 步：把 rows 变成一张"表格"，并给 5 列起名字 ----------
df = pd.DataFrame(rows, columns=['工单号', '退货原因', '退款金额', '退货日期', '是否VIP'])


# ---------- 第 7 步：把表格保存成 Excel ----------
# index=False 的意思是：不要把 pandas 自动编号的 0/1/2… 也写进 Excel
df.to_excel('工单数据.xlsx', index=False)


# ---------- 第 8 步：打印几句话，确认存好了 ----------
# df.head(3) = 只看表格最前面 3 行（检查一下长什么样）
print('已生成：工单数据.xlsx')
print('共', len(df), '行')
print('前 3 行长这样：')
print(df.head(3))
